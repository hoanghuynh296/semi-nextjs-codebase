#!/usr/bin/env node
// /semi-brand helper: creates, edits and updates a brand kit repo (docs/BRANDS.md). Zero external deps; the colour
// work is done by the kit's own @semi/ui (semi-brand build).
//   node brand.mjs create --cwd <dir> --name "3D Noobs" --package @3dnoobs/brand --primary "#00AE42"
//        [--secondary "#hex"] [--neutral tinted|preset] [--style flat] [--allow flat,soft]
//        [--sans Geist] [--display "Montserrat Alternates"]
//   node brand.mjs set --cwd <dir> primary=#00C853 secondary=none neutral=preset allow=flat,soft
//        style=flat sans=Inter display=Inter        edit brand.json, then build
//   node brand.mjs build|check --cwd <dir>          the kit's semi-brand
//   node brand.mjs preview --cwd <dir> [--port N]   serve the kit's preview site (http://localhost:4600); keep it running
//   node brand.mjs site --cwd <dir>                 static preview site in .preview/out (what the Pages workflow builds)
//   node brand.mjs pages --cwd <dir>                turn on GitHub Pages (source: GitHub Actions) for the kit repo
//   node brand.mjs update --cwd <dir>               newest @semi/ui, "semi" range, rebuild, suggest the version bump
//   node brand.mjs bump --cwd <dir> patch|minor|major|<x.y.z>
//   node brand.mjs colors <logo.svg>                brand colours used in an SVG logo (most used first, greys left out)
//   create … --from <brand.json>                    take every choice from a brand.json (the docs Brand preview copies one)
//   set keys for the guideline: tone=friendly|neutral|formal address=bạn we="3D Noobs" emoji=false
//        accent=restrained|balanced|expressive secondaryRole=highlight|badge|illustration imagery="…"
//        product="…" audience="…" personality=nhanh,vui,đáng tin logo=assets/logo.svg logoDark=… mark=…
//        signature: density=compact|regular|airy scale=even|contrast title=light|regular|strong figures=sans|display
//        motif=mark|dots|lines|grid|none (auto = back to what the brief implies)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { cmpSemver, detectPkgManager, resolveTargetSpec, runLocal } from "../../semi-new-app/scripts/setup.mjs";

const argv = process.argv.slice(2);
const cmd = argv[0];
let cwd = process.cwd();
const opts = {};
const pairs = [];
for (let i = 1; i < argv.length; i++) {
  const a = argv[i];
  if (a === "--cwd" && argv[i + 1]) cwd = resolve(argv[++i]);
  else if (a.startsWith("--") && argv[i + 1] !== undefined) opts[a.slice(2)] = argv[++i];
  else pairs.push(a);
}
const brandPath = join(cwd, "brand.json");
const pkgPath = join(cwd, "package.json");
const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const writeJson = (p, v) => writeFileSync(p, JSON.stringify(v, null, 2) + "\n");
const semiVersion = () => {
  try {
    return readJson(join(cwd, "node_modules", "@semi", "ui", "package.json")).version;
  } catch {
    return null;
  }
};
const kitBin = (sub, extra = []) => runLocal(cwd, "semi-brand", [sub, ...extra]);

/** What a kit needs to build and publish its preview site (Next.js runs it; the template ships in @semi/ui). */
const PREVIEW_DEPS = { next: "^16.0.0", react: "^19.0.0", "react-dom": "^19.0.0", tailwindcss: "^4.1.0", "@tailwindcss/postcss": "^4.1.0" };
const SCRIPTS = { build: "semi-brand build", check: "semi-brand check", preview: "semi-brand preview", site: "semi-brand site" };
const PAGES_WORKFLOW = `# Builds the brand preview site (semi-brand site) and publishes it on GitHub Pages at every push to main.
# One-time setup: Settings → Pages → Source: GitHub Actions (or: node brand.mjs pages). Generated by /semi-brand.
name: Brand preview

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: true

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 24
          cache: npm
      - run: npm ci
      - run: npx semi-brand check
      - run: npx semi-brand site
        env:
          SEMI_BRAND_BASE_PATH: /\${{ github.event.repository.name }}
      - uses: actions/configure-pages@v5
      - uses: actions/upload-pages-artifact@v3
        with:
          path: .preview/out

  deploy:
    needs: build
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: \${{ steps.deployment.outputs.page_url }}
    steps:
      - id: deployment
        uses: actions/deploy-pages@v4
`;

/** Add what an older or new kit lacks: preview deps and scripts, .gitignore lines, the Pages workflow. Returns true when package.json changed (needs an install). */
function scaffold() {
  const pkg = readJson(pkgPath);
  let changed = false;
  pkg.scripts ||= {};
  for (const [k, v] of Object.entries(SCRIPTS)) if (pkg.scripts[k] !== v) (pkg.scripts[k] = v), (changed = true);
  pkg.devDependencies ||= {};
  for (const [k, v] of Object.entries(PREVIEW_DEPS)) if (!pkg.devDependencies[k]) (pkg.devDependencies[k] = v), (changed = true);
  if (pkg.exports && !pkg.exports["./dist/logo/*"]) (pkg.exports["./dist/logo/*"] = "./dist/logo/*"), (changed = true); // logo files (brand.json "logo")
  if (changed) writeJson(pkgPath, pkg);
  const ignore = join(cwd, ".gitignore");
  const lines = existsSync(ignore) ? readFileSync(ignore, "utf8").split("\n").filter(Boolean) : [];
  for (const l of ["node_modules/", ".preview/"]) if (!lines.includes(l)) lines.push(l);
  writeFileSync(ignore, lines.join("\n") + "\n");
  const wf = join(cwd, ".github", "workflows", "brand-pages.yml");
  mkdirSync(join(cwd, ".github", "workflows"), { recursive: true });
  if (!existsSync(wf) || readFileSync(wf, "utf8") !== PAGES_WORKFLOW) writeFileSync(wf, PAGES_WORKFLOW);
  return changed;
}

/** owner/repo of the kit's GitHub remote, or null. */
function githubRepo() {
  const r = spawnSync("git", ["remote", "get-url", "origin"], { cwd, encoding: "utf8" });
  const m = (r.stdout || "").trim().match(/github\.com[:/]([\w.-]+)\/([\w.-]+?)(?:\.git)?$/);
  return m ? { owner: m[1], repo: m[2] } : null;
}
const pagesUrl = (gh) => `https://${gh.owner.toLowerCase()}.github.io/${gh.repo}/`;

function installSemi(spec) {
  const pkg = readJson(pkgPath);
  (pkg.devDependencies ||= {})["@semi/ui"] = spec;
  writeJson(pkgPath, pkg);
  const pm = detectPkgManager(cwd);
  // Name the package: a bare `npm install` keeps the commit package-lock.json already has for a git dependency, so a
  // new tag in package.json would never be installed.
  const args = pm === "npm" ? ["install", "--install-links", "-D", `@semi/ui@${spec}`] : ["add", "-D", `@semi/ui@${spec}`];
  return spawnSync(pm, args, { cwd, stdio: "inherit" }).status === 0;
}

/** Brand tokens of the last build (dist/brand.json), for comparing before / after an update. */
const builtTokens = () => (existsSync(join(cwd, "dist", "brand.json")) ? readJson(join(cwd, "dist", "brand.json")) : null);

/** Which part of a kit changed between two builds: "major" (colours / fonts people see), "minor" (new options), "patch". */
function changeLevel(before, after) {
  if (!before) return "major";
  const pick = (t) => JSON.stringify({ primary: t.primary, secondary: t.secondary, themes: t.themes, neutrals: t.neutrals, fonts: t.fonts });
  if (pick(before) !== pick(after)) {
    const removed = before.styles.allowed.some((s) => !after.styles.allowed.includes(s));
    const onlyAdded = !removed && JSON.stringify(before.primary) === JSON.stringify(after.primary) && JSON.stringify(before.themes) === JSON.stringify(after.themes) &&
      Object.keys(before.neutrals).every((s) => JSON.stringify(before.neutrals[s]) === JSON.stringify(after.neutrals[s])) && JSON.stringify(before.fonts) === JSON.stringify(after.fonts);
    return onlyAdded ? "minor" : "major";
  }
  // Guideline: a new logo is visible in every product (major); voice, colour use, brief and imagery change how agents
  // write and compose, not what is on screen today (minor).
  const g = (t, k) => JSON.stringify(t.guide?.[k] ?? null);
  if (g(before, "logo") !== g(after, "logo")) return before.guide?.logo ? "major" : "minor";
  // The signature (density, type, motif) changes every screen a little: minor, like a new allowed style.
  if (["voice", "color", "brief", "imagery", "signature"].some((k) => g(before, k) !== g(after, k))) return "minor";
  return JSON.stringify(before.styles) !== JSON.stringify(after.styles) ? "minor" : "patch";
}

const README = (b) => `# ${b.name}: brand kit

Bộ nhận diện của **${b.name}** trên Semi Design System. File duy nhất người sửa là \`brand.json\`; mọi file trong
\`dist/\`, \`BRAND.md\` và \`AGENTS.brand.md\` do \`semi-brand build\` sinh ra.

- Guideline: [BRAND.md](BRAND.md)
- Xem trước: \`npm run preview\` (http://localhost:4600); bản online: GitHub Pages của repo này (workflow
  \`.github/workflows/brand-pages.yml\` build lại mỗi lần push lên main)
- Đổi lựa chọn: \`/semi-brand\` (hoặc sửa \`brand.json\`, rồi \`npm run build\`)
- Bản Semi mới: \`/semi-brand update\`
- Dùng trong sản phẩm mới: \`/semi-new-app --brand github:<owner>/<repo>\`; sản phẩm có sẵn: \`/semi-sync\`

Hướng dẫn đầy đủ: \`node_modules/@semi/ui/docs/BRANDS.md\`.
`;

function applyPair(brand, key, value) {
  const v = value === "none" || value === "null" ? null : value;
  if (key === "primary" || key === "secondary" || key === "name" || key === "neutral") brand[key] = v;
  else if (key === "allow") brand.styles.allowed = v.split(",").map((x) => x.trim()).filter(Boolean);
  else if (key === "style") brand.styles.default = v;
  else if (key === "sans" || key === "display") brand.fonts[key] = v;
  else if (["tone", "address", "we", "emoji"].includes(key)) {
    brand.voice ||= {};
    if (v === null) delete brand.voice[key];
    else brand.voice[key] = key === "emoji" ? v === "true" : v;
  } else if (key === "accent" || key === "secondaryRole") {
    brand.color ||= {};
    if (v === null) delete brand.color[key];
    else brand.color[key] = v;
  } else if (key === "product" || key === "audience" || key === "personality" || key === "tagline") {
    brand.brief ||= {};
    if (v === null) delete brand.brief[key];
    else brand.brief[key] = key === "personality" ? v.split(",").map((x) => x.trim()).filter(Boolean) : v;
  } else if (key === "logo" || key === "logoDark" || key === "mark") {
    const k = { logo: "full", logoDark: "fullDark", mark: "mark" }[key];
    if (v === null && k === "full") delete brand.logo;
    else {
      brand.logo ||= {};
      if (v === null) delete brand.logo[k];
      else brand.logo[k] = v;
    }
  } else if (key === "imagery") {
    if (v === null) delete brand.imagery;
    else brand.imagery = v;
  } else if (key === "density" || key === "motif") {
    // "auto" = back to what the brief implies; motif=none is a real choice (no motif).
    if (value === "auto") delete brand[key];
    else brand[key] = value;
  } else if (key === "scale" || key === "title" || key === "figures") {
    brand.typography ||= {};
    if (value === "auto") delete brand.typography[key];
    else brand.typography[key] = value;
    if (!Object.keys(brand.typography).length) delete brand.typography;
  } else
    throw new Error(
      `không biết khoá "${key}" (primary, secondary, name, neutral, allow, style, sans, display, tone, address, we, emoji, accent, secondaryRole, product, audience, personality, tagline, logo, logoDark, mark, imagery, density, scale, title, figures, motif)`,
    );
}

/** Colours an SVG logo uses (fill, stroke, stop-color, style), most used first; near-greys (black text, white) left out. */
function svgColors(svg) {
  const count = new Map();
  const hex = (r, g, b) => `#${[r, g, b].map((x) => Math.round(x).toString(16).padStart(2, "0")).join("")}`.toUpperCase();
  for (const m of svg.matchAll(/(?:fill|stroke|stop-color|color)\s*[:=]\s*["']?\s*(#[0-9a-f]{3,8}\b|rgba?\([^)]*\))/gi)) {
    let c = m[1];
    if (c.startsWith("#")) {
      let h = c.slice(1);
      if (h.length === 3 || h.length === 4) h = [...h.slice(0, 3)].map((x) => x + x).join("");
      c = `#${h.slice(0, 6).toUpperCase()}`;
    } else {
      const [r, g, b] = c.match(/[\d.]+/g).map(Number);
      c = hex(r, g, b);
    }
    count.set(c, (count.get(c) ?? 0) + 1);
  }
  return [...count.entries()]
    .map(([c, n]) => {
      const [r, g, b] = [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
      return { hex: c, uses: n, saturation: (Math.max(r, g, b) - Math.min(r, g, b)) / 255 };
    })
    .filter((x) => x.saturation >= 0.12)
    .sort((a, b) => b.uses - a.uses || b.saturation - a.saturation);
}

if (cmd === "colors") {
  const file = pairs[0] ? resolve(cwd, pairs[0]) : null;
  if (!file || !existsSync(file)) {
    console.error("cần file logo: node brand.mjs colors <logo.svg>");
    process.exit(2);
  }
  if (!/\.svg$/i.test(file)) {
    console.error("Chỉ đọc được màu từ SVG. Ảnh PNG / JPG: xem ảnh và đọc màu bằng mắt, rồi hỏi người dùng mã hex chính xác (hoặc xin file SVG).");
    process.exit(3);
  }
  const list = svgColors(readFileSync(file, "utf8"));
  if (!list.length) console.log("Logo không có màu nào ngoài đen / trắng / xám: hỏi người dùng màu chính.");
  else for (const c of list) console.log(`${c.hex}  dùng ${c.uses} lần`);
  process.exit(0);
}

if (cmd === "create") {
  if (opts.from) {
    // A brand.json from the docs Brand preview or another kit: its choices become the flags below.
    const src = readJson(resolve(cwd, opts.from));
    for (const k of ["name", "package", "primary", "secondary", "neutral"]) if (src[k] && !opts[k]) opts[k] = src[k];
    if (src.styles && !opts.style) (opts.style = src.styles.default), (opts.allow = src.styles.allowed.join(","));
    if (src.fonts) (opts.sans ||= src.fonts.sans), (opts.display ||= src.fonts.display);
    opts.guide = JSON.stringify(Object.fromEntries(["brief", "logo", "voice", "color", "imagery", "density", "typography", "motif"].filter((k) => src[k] !== undefined).map((k) => [k, src[k]])));
  }
  if (existsSync(brandPath)) {
    console.error(`${brandPath} đã có: đây là brand kit có sẵn. Sửa bằng: node brand.mjs set …`);
    process.exit(10);
  }
  for (const k of ["name", "package", "primary"])
    if (!opts[k]) {
      console.error(`thiếu --${k}`);
      process.exit(2);
    }
  mkdirSync(cwd, { recursive: true });
  const target = resolveTargetSpec();
  const style = opts.style || "flat";
  const brand = {
    name: opts.name,
    package: opts.package,
    primary: opts.primary,
    secondary: opts.secondary && opts.secondary !== "none" ? opts.secondary : null,
    neutral: opts.neutral || "tinted",
    styles: { default: style, allowed: (opts.allow || style).split(",").map((s) => s.trim()) },
    fonts: { sans: opts.sans || "Geist", display: opts.display || "Montserrat Alternates" },
    ...(opts.guide ? JSON.parse(opts.guide) : {}),
    semi: `^${target.version}`,
  };
  writeJson(brandPath, brand);
  writeJson(pkgPath, {
    name: opts.package,
    version: "0.1.0",
    private: true,
    description: `${opts.name} brand kit on the Semi Design System`,
    type: "module",
    files: ["dist", "brand.json", "BRAND.md", "AGENTS.brand.md"],
    exports: {
      "./dist/brand.css": "./dist/brand.css",
      "./dist/logo/*": "./dist/logo/*",
      "./brand.json": "./dist/brand.json",
      "./BRAND.md": "./BRAND.md",
      "./AGENTS.brand.md": "./AGENTS.brand.md",
      "./package.json": "./package.json",
    },
    scripts: { ...SCRIPTS },
    devDependencies: { "@semi/ui": target.spec, ...PREVIEW_DEPS },
  });
  scaffold();
  writeFileSync(join(cwd, "README.md"), README(brand));
  console.log(`Cài @semi/ui (${target.spec}) cho brand kit…`);
  if (!installSemi(target.spec)) process.exit(1);
  brand.semi = `^${semiVersion() || target.version}`; // the version really installed
  writeJson(brandPath, brand);
  const r = kitBin("build");
  console.log(`\nBrand kit ${opts.name} đã tạo ở ${cwd}.`);
  console.log(`Xem trước ở máy: node brand.mjs preview --cwd "${cwd}" (chạy nền), rồi mở http://localhost:4600`);
  process.exit(r.status || 0);
}

if (cmd === "set") {
  if (!existsSync(brandPath)) {
    console.error("chưa có brand.json: tạo brand kit bằng node brand.mjs create …");
    process.exit(2);
  }
  const brand = readJson(brandPath);
  const before = builtTokens();
  try {
    for (const p of pairs) {
      const i = p.indexOf("=");
      applyPair(brand, p.slice(0, i), p.slice(i + 1));
    }
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
  writeJson(brandPath, brand);
  const r = kitBin("build");
  if (r.status === 0) {
    const level = changeLevel(before, builtTokens());
    console.log(`Thay đổi này là mức ${level} (sản phẩm: ${level === "major" ? "/semi-sync sẽ hỏi trước vì giao diện đổi" : "/semi-sync tự nhận"}). Trang preview đang chạy tự cập nhật.`);
  }
  process.exit(r.status || 0);
}

if (["build", "check", "preview", "site", "storybook"].includes(cmd)) process.exit(kitBin(cmd, cmd === "preview" && opts.port ? ["--port", opts.port] : []).status || 0);

if (cmd === "pages") {
  // Turns on GitHub Pages (source: GitHub Actions) for the kit repo, so brand-pages.yml can publish the preview.
  const gh = githubRepo();
  if (!gh) {
    console.error("Repo chưa có remote GitHub (origin). Tạo repo và push trước: gh repo create <owner>/<repo> --source . --push");
    process.exit(2);
  }
  const api = spawnSync("gh", ["api", "-X", "POST", `repos/${gh.owner}/${gh.repo}/pages`, "-f", "build_type=workflow"], { encoding: "utf8" });
  const already = /already|409/.test(api.stderr || "");
  if (api.status !== 0 && !already) {
    console.error(`Không bật được GitHub Pages (${(api.stderr || "").trim() || "cần gh đã đăng nhập"}).`);
    console.error("Bật tay: Settings → Pages → Build and deployment → Source: GitHub Actions. Repo private cần gói GitHub có Pages cho private.");
    process.exit(1);
  }
  console.log(`GitHub Pages đã bật (GitHub Actions). Sau lần push kế tiếp lên main, trang preview ở ${pagesUrl(gh)}`);
  process.exit(0);
}

if (cmd === "update") {
  if (!existsSync(brandPath)) {
    console.error("chưa có brand.json ở đây: /semi-brand update chạy trong repo brand kit");
    process.exit(2);
  }
  const before = builtTokens();
  const from = semiVersion();
  const target = resolveTargetSpec();
  const needsInstall = scaffold(); // older kits get the preview site, its scripts and the Pages workflow
  if (from && cmpSemver(target.version, from) <= 0 && !needsInstall) console.log(`@semi/ui đã mới nhất (${from}); chỉ sinh lại.`);
  else {
    console.log(`@semi/ui ${from || "?"} → ${target.version}`);
    if (!installSemi(target.spec)) process.exit(1);
  }
  if (semiVersion() !== target.version && !process.env.SEMI_UI_SOURCE) {
    console.error(`@semi/ui: đã cài ${semiVersion()} nhưng cần ${target.version}. Xoá node_modules/@semi rồi chạy lại update.`);
    process.exit(1);
  }
  const brand = readJson(brandPath);
  brand.semi = `^${semiVersion() || target.version}`;
  writeJson(brandPath, brand);
  const r = kitBin("build");
  if (r.status !== 0) process.exit(r.status);
  const level = changeLevel(before, builtTokens());
  const version = readJson(pkgPath).version;
  console.log(`\nKit sinh lại xong. Mức thay đổi: ${level} → đề xuất bump ${level} từ ${version} (node brand.mjs bump --cwd "${cwd}" ${level}).`);
  process.exit(0);
}

if (cmd === "bump") {
  const pkg = readJson(pkgPath);
  const level = pairs[0];
  const [a, b, c] = pkg.version.split(".").map(Number);
  const next = /^\d+\.\d+\.\d+$/.test(level || "") ? level : level === "major" ? `${a + 1}.0.0` : level === "minor" ? `${a}.${b + 1}.0` : level === "patch" ? `${a}.${b}.${c + 1}` : null;
  if (!next) {
    console.error("bump cần patch | minor | major | x.y.z");
    process.exit(2);
  }
  pkg.version = next;
  writeJson(pkgPath, pkg);
  console.log(`${pkg.name} ${a}.${b}.${c} → ${next}. Commit, rồi gắn tag v${next} và push (sản phẩm cài theo tag).`);
  process.exit(0);
}

console.log("usage: brand.mjs create | set | build | check | preview | site | storybook | pages | update | bump  (xem đầu file)");
process.exit(cmd ? 2 : 0);
