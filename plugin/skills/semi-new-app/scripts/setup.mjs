/**
 * The gate that holds outside Claude Code too (0.30.0): `lint` runs semi-lint first, and a CI workflow runs
 * `semi-lint --ci` (the baseline and skips may not grow) and `tsc` on every push and pull request. Idempotent; returns
 * what it changed. Not wired into `build`, so an urgent fix still builds.
 */
export function wireLintGate(appDir) {
  const changed = [];
  const pkgPath = join(appDir, "package.json");
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  pkg.scripts ||= {};
  if (pkg.scripts["semi:lint"] !== "semi-lint") (pkg.scripts["semi:lint"] = "semi-lint"), changed.push("script semi:lint");
  const lint = pkg.scripts.lint;
  if (!lint) (pkg.scripts.lint = "semi-lint"), changed.push("script lint");
  else if (!/\bsemi-lint\b/.test(lint)) (pkg.scripts.lint = `semi-lint && ${lint}`), changed.push("script lint ← semi-lint");
  if (changed.length) writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
  const root = gitRoot(appDir);
  const wf = join(root, ".github", "workflows", "semi.yml");
  if (!existsSync(wf)) {
    const rel = relative(root, resolve(appDir)).split(sep).join("/") || ".";
    const pm = detectPkgManager(appDir);
    mkdirSync(dirname(wf), { recursive: true });
    writeFileSync(
      wf,
      `# Semi design-system gate (generated by /semi-new-app or /semi-check): semi-lint and tsc on every push and pull
# request. --ci also fails when semi-lint-baseline.json or a skip in semi-lint.json grew against the base branch.
name: Semi

on:
  push:
    branches: [main]
  pull_request:

jobs:
  semi:
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: ${rel}
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/setup-node@v4
        with:
          node-version: 24
${pm === "pnpm" ? "      - uses: pnpm/action-setup@v4\n" : ""}      - run: ${INSTALL[pm] ?? "npm ci"}
      - run: npx semi-lint --ci
        env:
          SEMI_LINT_BASE: origin/\${{ github.base_ref || 'main' }}
      - run: npx tsc --noEmit
`,
    );
    changed.push(relative(appDir, wf).split(sep).join("/") || wf);
  }
  return changed;
}

/** The install command (own syntax of each manager) for one package: { pm, args, cmd }. Run it in the app folder. */
export function addPackageCommand(appDir, spec, { dev = false } = {}) {
  const pm = detectPkgManager(appDir);
  const args = pm === "npm" ? ["install", "--install-links", ...(dev ? ["-D"] : []), spec] : ["add", ...(dev ? ["-D"] : []), spec];
  return { pm, args, cmd: `${pm} ${args.join(" ")}` };
}

/** "1.2.3" vs "1.10.0" → -1 / 0 / 1 (a leading "v" is ignored). */
export function cmpSemver(a, b) {
  const pa = String(a).replace(/^v/, "").split(".").map(Number);
  const pb = String(b).replace(/^v/, "").split(".").map(Number);
  for (let i = 0; i < 3; i++) if ((pa[i] || 0) !== (pb[i] || 0)) return (pa[i] || 0) < (pb[i] || 0) ? -1 : 1;
  return 0;
}

/**
 * Does version satisfy a brand's "semi" range? Forms: "^1.2.0" / "~1.2.0" / "1.2.0" (caret on 0.x pins the minor, as npm
 * does) and comparator ranges ">=0.24.0 <1.0.0" (space-separated >=, >, <=, <, =). The comparator form is what
 * `semi-brand` writes: "this minor or later, below the next major". Anything else matches every version.
 */
export function satisfies(version, range) {
  if (!range) return true;
  const text = String(range).trim();
  const cmp = text.split(/\s+/);
  if (cmp.every((c) => /^(>=|<=|>|<|=)\d+\.\d+(\.\d+)?$/.test(c))) {
    return cmp.every((c) => {
      const [, op, v] = c.match(/^(>=|<=|>|<|=)(.+)$/);
      const d = cmpSemver(version, v);
      return op === ">=" ? d >= 0 : op === ">" ? d > 0 : op === "<=" ? d <= 0 : op === "<" ? d < 0 : d === 0;
    });
  }
  const m = text.match(/^([\^~]?)(\d+)\.(\d+)(?:\.(\d+))?$/);
  if (!m) return true;
  const [maj, min, pat] = [+m[2], +m[3], +(m[4] || 0)];
  const v = String(version).replace(/^v/, "").split(".").map(Number);
  if (cmpSemver(version, `${maj}.${min}.${pat}`) < 0) return false;
  if (m[1] === "^") return maj > 0 ? v[0] === maj : min > 0 ? v[0] === 0 && v[1] === min : v[0] === 0 && v[1] === 0 && v[2] === pat;
  if (m[1] === "~") return v[0] === maj && v[1] === min;
  return cmpSemver(version, `${maj}.${min}.${pat}`) === 0;
}

/** The range `semi-brand` writes for a @semi/ui version: this minor or later, below the next major (">=0.26.0 <1.0.0"). */
export function brandSemiRange(version) {
  const [maj, min] = String(version).replace(/^v/, "").split(".").map(Number);
  return `>=${maj}.${min}.0 <${maj + 1}.0.0`;
}

/** Release tags (vX.Y.Z) of a git repo, oldest first; null when the repo cannot be reached. */
export function gitTags(url) {
  const ls = spawnSync("git", ["ls-remote", "--tags", "--refs", url], { encoding: "utf8", timeout: 15000 });
  if (ls.status !== 0) return null;
  return (ls.stdout || "")
    .split(/\r?\n/)
    .map((l) => l.split("refs/tags/")[1])
    .filter((t) => t && /^v?\d+\.\d+\.\d+$/.test(t))
    .sort(cmpSemver);
}

/** github:owner/repo[#ref] → { url, base, ref }; null for other specs (file:, npm names). */
export function parseGithubSpec(spec) {
  const m = String(spec).match(/^(?:github:)?([\w.-]+)\/([\w.-]+?)(?:\.git)?(?:#(.+))?$/);
  if (!m || String(spec).startsWith("file:") || String(spec).startsWith(".")) return null;
  return { url: `https://github.com/${m[1]}/${m[2]}.git`, base: `github:${m[1]}/${m[2]}`, ref: m[3] ?? null };
}

/**
 * The plugin's own version (plugin/.claude-plugin/plugin.json). The marketplace pins the plugin to the release tag of
 * that version (docs/PLUGIN.md), so its rules describe exactly that @semi/ui. SEMI_PLUGIN_VERSION overrides it (tests).
 */
export function pluginVersion() {
  if (process.env.SEMI_PLUGIN_VERSION) return process.env.SEMI_PLUGIN_VERSION.replace(/^v/, "");
  try {
    return JSON.parse(readFileSync(join(PLUGIN_ROOT, ".claude-plugin", "plugin.json"), "utf8")).version ?? null;
  } catch {
    return null;
  }
}

/**
 * The @semi/ui spec to install: the latest release tag, or the latest one inside `range` (a brand kit's "semi") when
 * given, never newer than the plugin's own version (its rules and skills are written for that release; a newer tag
 * waits until the plugin is updated: `pluginBehind`). SEMI_UI_SOURCE overrides it (local checkouts, tests).
 */
export function resolveTargetSpec({ range } = {}) {
  if (process.env.SEMI_UI_SOURCE) {
    return { spec: process.env.SEMI_UI_SOURCE, version: "0.1.0" };
  }
  // SEMI_UI_TAGS="v0.24.0,v0.26.0,v1.0.0" replaces the remote tag list (tests).
  const tags = process.env.SEMI_UI_TAGS ? process.env.SEMI_UI_TAGS.split(",").map((t) => t.trim()).filter(Boolean).sort(cmpSemver) : gitTags(REPO_URL);
  if (!tags) {
    console.error(
      "ERROR: Cannot access private repository https://github.com/hoanghuynh296/semi-nextjs-codebase.\n" +
        "Action required: Run `gh auth login && gh auth setup-git` (or configure your GitHub SSH key), then run the command again.",
    );
    process.exit(2);
  }
  const own = pluginVersion();
  const known = own ? tags.filter((t) => cmpSemver(t, own) <= 0) : tags;
  const pool = known.length ? known : tags;
  const fitting = range ? pool.filter((t) => satisfies(t, range)) : pool;
  const latest = fitting[fitting.length - 1] || pool[pool.length - 1] || "v0.1.0";
  const newest = tags[tags.length - 1];
  return {
    spec: `${GITHUB_SPEC_BASE}#${latest}`,
    version: latest.replace(/^v/, ""),
    newest: newest?.replace(/^v/, ""),
    limited: Boolean(range && latest !== pool[pool.length - 1]),
    pluginBehind: Boolean(own && known.length && known.length < tags.length),
  };
}

