#!/usr/bin/env node
// tokens/tokens.json (single source) → tokens/tokens.css (Tailwind 4 @theme).
//   node scripts/build-tokens.mjs           write tokens/tokens.css
//   node scripts/build-tokens.mjs --check   exit 1 when tokens.css is stale (CI / pre-tag)
// Output is deterministic (same JSON → byte-identical CSS).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "tokens", "tokens.json");
const dst = join(root, "tokens", "tokens.css");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const tokens = JSON.parse(readFileSync(src, "utf8"));

const TITLES = {
  font: "Fonts (apps load Geist + Montserrat Alternates with next/font and expose --font-geist / --font-montserrat-alternates, or set --font-sans-family / --font-display-family)",
  brand: "Brand: primary-* = actions, focus, \"on\". Override per project in your own @theme after importing this file",
  status: "Status green (emerald-*): online, ready, success. Never an accent",
  semantic: "Semantic tokens (CSS variables mapped for Tailwind 4 @theme): auto-switches via data-theme=\"dark|light\"",
  gray: "Neutral gray (exact hex, zero blue cast)",
  palette: "Tailwind palettes pinned to v3 hex (v4 OKLCH shifts hues)",
  scale: "v3 scale semantics for rounded / shadow / blur / ring; radius scale lg (controls) / xl (cards) / 2xl (panels)",
  type: "Type scale: text-caption 11 · label 12 · ui 13 · ui-lg 14 · title 15 · title-lg 16 · kpi 18 · heading-sm 20 · heading 22 · heading-lg 24 · display 26",
  motion: "Easing (ease-out-soft for entering, ease-in-soft for leaving)",
  z: "Global layers (utilities z-sticky … z-tooltip); local stacking inside a component keeps z-10 / z-20",
};

let out = `/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json — do not edit by hand.\n   @semi/ui ${pkg.version} · import after "tailwindcss": @import "@semi/ui/tokens.css"; */\n@theme {\n`;

// Semantic tokens: the themed value lives in a source variable (--semi-canvas) that each theme scope sets.
// Utilities read it through `@theme inline` (bg-canvas → var(--semi-canvas)), so they follow the nearest
// data-theme scope with no self-referencing --color-* variable. --color-* stays set per scope for app CSS.
const darkVars = [];
const lightVars = [];
const inlineVars = [];
const compatVars = [];
const zKeys = [];
const srcVar = (key) => `--semi-${key.replace(/^color-/, "")}`;

for (const [group, entries] of Object.entries(tokens)) {
  if (group.startsWith("$")) continue;
  if (group === "semantic") {
    for (const [key, raw] of Object.entries(entries)) {
      const note = raw.note ? ` /* ${raw.note} */` : "";
      // An aliased key (color-text-contrast → color-contrast) only gets the alias as a utility (text-contrast).
      inlineVars.push(`  --${raw.alias ?? key}: var(${srcVar(key)});${note}`);
      darkVars.push(`  ${srcVar(key)}: ${raw.dark};`);
      lightVars.push(`  ${srcVar(key)}: ${raw.light};`);
      compatVars.push(`  --${key}: var(${srcVar(key)});`);
      if (raw.alias) compatVars.push(`  --${raw.alias}: var(${srcVar(key)});`);
    }
    continue;
  }
  if (group === "z") zKeys.push(...Object.keys(entries));
  out += `\n  /* ${TITLES[group] ?? group} */\n`;
  for (const [key, raw] of Object.entries(entries)) {
    const value = typeof raw === "string" ? raw : raw.value;
    const note = typeof raw === "string" ? "" : raw.note ? ` /* ${raw.note} */` : "";
    out += `  --${key}: ${value};${note}\n`;
  }
}
out += "}\n\n";

if (darkVars.length > 0) {
  out += `/* ${TITLES.semantic} */\n@theme inline {\n${inlineVars.join("\n")}\n}\n\n`;
  out += `/* Semantic Tokens: Dark Mode (Default) */\n:root,\n[data-theme="dark"],\n[data-theme="system"],\n.dark {\n${darkVars.join("\n")}\n}\n\n`;
  out += `/* Semantic Tokens: Light Mode */\n[data-theme="light"],\n.light {\n${lightVars.join("\n")}\n}\n\n`;
  out += `/* data-theme="system": follows the OS without JS (ThemeScript resolves it to dark|light before paint) */\n@media (prefers-color-scheme: light) {\n  [data-theme="system"] {\n${lightVars.map((l) => "  " + l).join("\n")}\n  }\n}\n\n`;
  out += `/* --color-* runtime variables for app CSS (var(--color-panel)), re-resolved in every theme scope */\n:root,\n[data-theme],\n.dark,\n.light {\n${compatVars.join("\n")}\n}\n\n`;
  out += zKeys.map((k) => `@utility ${k} {\n  z-index: var(--${k});\n}\n`).join("") + "\n";
  out += `/* Utility fallbacks & direct semantic text/bg/border helpers */\n@layer utilities {\n` +
    `  .text-contrast { color: var(--color-text-contrast); }\n` +
    `  .text-body { color: var(--color-text-body); }\n` +
    `  .text-muted { color: var(--color-text-muted); }\n` +
    `  .bg-canvas { background-color: var(--color-canvas); }\n` +
    `  .bg-app { background-color: var(--color-app); }\n` +
    `  .bg-panel { background-color: var(--color-panel); }\n` +
    `  .bg-field { background-color: var(--color-field); }\n` +
    `  .bg-raised { background-color: var(--color-raised); }\n` +
    `  .border-line { border-color: var(--color-line); }\n` +
    `  .border-divider { border-color: var(--color-divider); }\n` +
    `}\n`;
}

if (process.argv.includes("--check")) {
  const cur = existsSync(dst) ? readFileSync(dst, "utf8") : "";
  if (cur !== out) {
    console.error("tokens/tokens.css is stale: run node scripts/build-tokens.mjs");
    process.exit(1);
  }
  console.log("tokens.css up to date");
} else {
  writeFileSync(dst, out);
  console.log(`wrote tokens/tokens.css (${out.split("\n").filter((l) => l.trim().startsWith("--")).length} tokens)`);
}
