#!/usr/bin/env node
// tokens/tokens.json (single source) → tokens/tokens.css (Tailwind 4 @theme).
//   node scripts/build-tokens.mjs           write tokens/tokens.css
//   node scripts/build-tokens.mjs --check   exit 1 when tokens.css is stale (CI / pre-tag)
// Output is deterministic (same JSON → byte-identical CSS).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "tokens", "tokens.json");
const dst = join(root, "tokens", "tokens.css");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const tokens = JSON.parse(readFileSync(src, "utf8"));

const TITLES = {
  font: "Fonts (apps load Geist + Montserrat Alternates with next/font and expose --font-geist / --font-montserrat-alternates, or set --font-sans-family / --font-display-family)",
  brand: "Brand: primary-* = actions, focus, \"on\". Override per project in your own @theme after importing this file",
  status: "Status green (emerald-*): online, ready, success. Never an accent",
  surface: "Surfaces & lines (dark theme): bg-canvas / bg-app / bg-panel / bg-field / bg-raised / border-line",
  gray: "Neutral gray (exact hex, zero blue cast)",
  palette: "Tailwind palettes pinned to v3 hex (v4 OKLCH shifts hues)",
  scale: "v3 scale semantics for rounded / shadow / blur / ring",
};

let out = `/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json — do not edit by hand.\n   @semi/ui ${pkg.version} · import after "tailwindcss": @import "@semi/ui/tokens.css"; */\n@theme {\n`;
for (const [group, entries] of Object.entries(tokens)) {
  if (group.startsWith("$")) continue;
  out += `\n  /* ${TITLES[group] ?? group} */\n`;
  for (const [key, raw] of Object.entries(entries)) {
    const value = typeof raw === "string" ? raw : raw.value;
    const note = typeof raw === "string" ? "" : raw.note ? ` /* ${raw.note} */` : "";
    out += `  --${key}: ${value};${note}\n`;
  }
}
out += "}\n";

if (process.argv.includes("--check")) {
  const cur = existsSync(dst) ? readFileSync(dst, "utf8") : "";
  if (cur !== out) {
    console.error("tokens/tokens.css is stale: run node scripts/build-tokens.mjs");
    process.exit(1);
  }
  console.log("tokens.css up to date");
} else {
  writeFileSync(dst, out);
  console.log(`wrote tokens/tokens.css (${out.split("\n").filter((l) => l.trim().startsWith("--")).length} tokens)`);
}
