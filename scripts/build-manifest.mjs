#!/usr/bin/env node
// Machine-readable inventory of @semi/ui for agents and docs, generated from the source so it cannot drift.
//   node scripts/build-manifest.mjs          write components.json, the generated list in docs/QUICK_REF.md and the
//                                            agent files of the Storybook (public/llms.txt, llms-full.txt, docs/…)
//   node scripts/build-manifest.mjs --check  exit 1 when any of them is stale (npm run check)
// Each entry: name, kind (component | hook | function | constant | type-scale), module, client, summary (JSDoc or
// the file's header comment), props (names of the destructured parameters, for components).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildDocs, GROUPS } from "./build-docs.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const tokens = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8"));

const clean = (c) =>
  c
    .trim()
    .replace(/^\/\*\*?|\*\/$/g, "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, "").replace(/^\s*\/\/\s?/, "").trim())
    .filter((l) => l && !l.startsWith("@") && !/^</.test(l))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();

function headerComment(src) {
  const lines = src.split("\n");
  const out = [];
  for (const l of lines) {
    if (/^"use client"|^\s*$/.test(l) && !out.length) continue;
    if (/^\/\//.test(l)) out.push(l);
    else break;
  }
  return clean(out.join("\n")).split(/(?<=\.)\s/)[0] ?? "";
}

/** Destructured prop names of `export function X({ a, b = 1, c: alias, ...rest }` (top level of the pattern only). */
function propsOf(src, at) {
  const open = src.indexOf("(", at);
  if (src[open + 1] !== "{") return [];
  let depth = 0;
  let i = open + 1;
  let body = "";
  for (; i < src.length; i++) {
    const ch = src[i];
    if ("{[(".includes(ch)) depth++;
    if ("}])".includes(ch)) depth--;
    body += ch;
    if (depth === 0) break;
  }
  const inner = body.slice(1, -1);
  const names = [];
  let d = 0;
  let cur = "";
  for (const ch of inner + ",") {
    if ("{[(<".includes(ch)) d++;
    if ("}])>".includes(ch)) d--;
    if (ch === "," && d === 0) {
      const m = cur.trim().match(/^(?:\.\.\.)?["']?([\w-]+)["']?/);
      if (m && !cur.trim().startsWith("...")) names.push(m[1]);
      cur = "";
    } else cur += ch;
  }
  return names;
}

function scanModule(rel) {
  const src = readFileSync(join(root, rel), "utf8");
  const client = /^\s*"use client"/.test(src);
  const header = headerComment(src);
  const entries = [];
  const rx = /(\/\*\*(?:(?!\*\/)[\s\S])*\*\/\s*)?export (?:const|function) ([A-Za-z_]\w*)/g;
  let m;
  while ((m = rx.exec(src))) {
    const name = m[2];
    const doc = m[1] ? clean(m[1]) : "";
    const after = src.slice(m.index + m[0].length, m.index + m[0].length + 40);
    const isFn = m[0].includes("function") || /^\s*(?::[^=]+)?=\s*(?:async\s*)?\(/.test(after);
    const kind = /^use[A-Z]/.test(name) ? "hook" : isFn && /^[A-Z]/.test(name) && rel.endsWith(".tsx") ? "component" : isFn ? "function" : "constant";
    const entry = { name, kind, module: rel, client, summary: doc || (kind === "component" ? header : "") };
    if (kind === "component") entry.props = propsOf(src, m.index + m[0].length);
    entries.push(entry);
  }
  return entries;
}

const files = [
  ...readdirSync(join(root, "src")).filter((f) => /\.tsx?$/.test(f) && f !== "index.ts" && f !== "iconCatalog.ts").map((f) => `src/${f}`),
  ...readdirSync(join(root, "styles")).filter((f) => /\.ts$/.test(f) && f !== "index.ts").map((f) => `styles/${f}`),
].sort();
const exportsIndex = readFileSync(join(root, "src/index.ts"), "utf8");
const publicModule = (rel) => rel.startsWith("styles/") || new RegExp(`"\\./${rel.slice(4).replace(/\.tsx?$/, "")}"`).test(exportsIndex);

const items = files.filter(publicModule).flatMap(scanModule);
const iconSrc = readFileSync(join(root, "src/Icon.tsx"), "utf8");
const iconBlock = iconSrc.slice(iconSrc.indexOf("export const ICONS = {"), iconSrc.indexOf("\n} as const", iconSrc.indexOf("export const ICONS = {")));
const iconNames = [...iconBlock.matchAll(/^ {2}([a-zA-Z0-9]+):/gm)].map((x) => x[1]);
const styleList = JSON.parse(readFileSync(join(root, "tokens/styles.json"), "utf8"));
const manifest = {
  $comment: "GENERATED by scripts/build-manifest.mjs — do not edit. Agents: pick components / constants from here, rules from docs/QUICK_REF.md.",
  package: pkg.name,
  version: pkg.version,
  import: { components: "@semi/ui", styles: "@semi/ui/styles", css: ["@semi/ui/tokens.css", "@semi/ui/base.css"] },
  tokens: {
    semantic: Object.keys(tokens.semantic).map((k) => k.replace(/^color-/, "").replace(/^text-/, "")),
    type: Object.keys(tokens.type),
    z: Object.keys(tokens.z),
    style: Object.keys(styleList.styles[0].tokens),
  },
  styles: { default: styleList.default, apply: '<html data-style="<id>" data-palette="<id>"> + "style" / "palette" in semi-lint.json; the first palette is the default (docs/STYLES.md)', list: styleList.styles.map(({ id, name, description, palettes }) => ({ id, name, description, palettes: palettes.map(({ id, name, description }) => ({ id, name, description })) })) },
  icons: iconNames,
  components: items.filter((i) => i.kind === "component"),
  hooks: items.filter((i) => i.kind === "hook"),
  functions: items.filter((i) => i.kind === "function"),
  constants: items.filter((i) => i.kind === "constant"),
};
const byModule = {};
for (const c of manifest.components) (byModule[c.module] ||= []).push(c.name);
const generated = [
  "<!-- generated:components:start (scripts/build-manifest.mjs) -->",
  `**Components (${manifest.components.length})** — full props / summaries in \`node_modules/@semi/ui/components.json\`:`,
  "",
  ...Object.entries(byModule).map(([mod, names]) => `- \`${mod.replace(/^src\//, "").replace(/\.tsx?$/, "")}\`: ${names.map((n) => `\`${n}\``).join(", ")}`),
  "",
  `**Hooks:** ${manifest.hooks.map((h) => `\`${h.name}\``).join(", ")} · **Functions:** ${manifest.functions.filter((f) => !f.module.startsWith("styles/") || f.name === "cn").map((f) => `\`${f.name}\``).join(", ")}`,
  "<!-- generated:components:end -->",
].join("\n");

const quickRefPath = join(root, "docs/QUICK_REF.md");
const quickRef = readFileSync(quickRefPath, "utf8");
const markerRx = /<!-- generated:components:start[\s\S]*?<!-- generated:components:end -->/;
const nextQuickRef = markerRx.test(quickRef) ? quickRef.replace(markerRx, generated) : `${quickRef.trimEnd()}\n\n## Component inventory\n\n${generated}\n`;

// Agent files served by the docs site (public/ is copied as is): llms.txt = index of every doc page and its markdown,
// llms-full.txt = that + the rule docs + every component doc; plus raw copies of the docs and the manifest.
const read = (rel) => readFileSync(join(root, rel), "utf8");
const typeNames = readdirSync(join(root, "src"))
  .filter((f) => /\.tsx?$/.test(f))
  .flatMap((f) => [...read(`src/${f}`).matchAll(/^export (?:type|interface) (\w+)/gm)].map((x) => x[1]));
const exported = new Set([...items.map((i) => i.name), ...typeNames]);
const built = buildDocs(root, { exported });
const docOf = Object.fromEntries(built.docs.flatMap((d) => d.components.map((c) => [c, d.id])));
for (const c of manifest.components) if (docOf[c.name]) c.doc = `docs/components/${docOf[c.name]}.md`;
const json = JSON.stringify(manifest, null, 2) + "\n";
const DOCS = [
  ["docs/QUICK_REF.md", "QUICK_REF.md", "Quick reference: the rules and imports to read before any UI change"],
  ["docs/DESIGN_SYSTEM.md", "DESIGN_SYSTEM.md", "Full design system rules (layout, colour, components, accessibility, anti-patterns)"],
  ["docs/COMPONENT_DOCS.md", "COMPONENT_DOCS.md", "How the component docs are built (examples/, meta.json, generated API) and how agents should use them"],
  ["docs/AGENT_TOOLS.md", "AGENT_TOOLS.md", "Agent tools: the semi CLI (search, docs, example, add) and the MCP server, and the page blocks"],
  ["docs/ICONS.md", "ICONS.md", "Semantic icon guide: which icon means what"],
  ["docs/BRANDS.md", "BRANDS.md", "Brands: brand kits (brand.json → brand.css), the step-by-step flow from a new brand to its first product, which command when"],
  ["docs/STYLES.md", "STYLES.md", "Styles (Flat, Soft, Sharp) and palettes: what each changes, how an app picks one"],
  ["plugin/rules/AGENTS.md", "agent-rules.md", "Rules block for a consumer app's AGENTS.md / CLAUDE.md"],
  ["tokens/tokens.css", "tokens.css", "Generated design tokens (CSS variables for both themes)"],
];
const llms = [
  `# Semi Design System (${pkg.name} v${pkg.version})`,
  "",
  "> The shared UI of every Semi app: semantic tokens that work in light and dark mode, React components (Next.js, Tailwind CSS 4) and the rules agents follow. Every component has a page with live examples and a markdown twin for agents.",
  "",
  `Install \`${pkg.name}\`, import components from \`${manifest.import.components}\`, class constants from \`${manifest.import.styles}\`, CSS ${manifest.import.css.map((c) => `\`${c}\``).join(" + ")}. Before writing UI read QUICK_REF.md; pick the component from docs/components/README.md, read its page, copy an example; never invent local colours, sizes or wrapper components; check with \`npx semi-lint\`.`,
  "",
  "In a project with the package installed, ask the docs instead of reading files: `npx semi search \"<need in words>\"`, `npx semi docs <Component>`, `npx semi example <id>`, `npx semi add <block>` (dashboard, list-page, settings-page, agent-run), or `npx semi mcp` as an MCP server (tools semi_search, semi_docs, semi_example, semi_props, semi_list, semi_block; the semi-design plugin starts it). Guide: docs/AGENT_TOOLS.md.",
  "",
  "## Machine-readable",
  "",
  `- [components.json](./components.json): all ${manifest.components.length} components, hooks and constants with props, summaries and their doc page`,
  "- [docs/components/README.md](./docs/components/README.md): every component doc by group, with when to use it",
  ...DOCS.map(([, out, what]) => `- [${out}](./docs/${out}): ${what}`),
  "- [llms-full.txt](./llms-full.txt): this file followed by all the docs above and every component doc",
  "",
  "## Pages",
  "",
  "- [Introduction](./): what Semi is, install, resources for agents",
  "- [Components](./components/): every component with a live example",
  "- [Foundations](./foundations/): surface tokens, type scale, icon registry",
  "- [Brand preview](./brand/): preview a brand on every page before creating its kit",
  "",
  "## Components",
  "",
  ...GROUPS.flatMap((g) => {
    const list = built.docs.filter((d) => d.group === g);
    return list.length
      ? [`### ${g}`, "", ...list.map((d) => `- [${d.title}](./components/${d.id}/) ([markdown](./docs/components/${d.id}.md)): ${d.description} Components: ${d.components.join(", ")}.`), ""]
      : [];
  }),
].join("\n");
const llmsFull = [
  llms,
  ...DOCS.filter(([src]) => src.endsWith(".md")).map(([src]) => `\n\n---\n\n<!-- ${src} -->\n\n${src === "docs/QUICK_REF.md" ? nextQuickRef : read(src)}`),
  ...built.docs.map((d) => `\n\n---\n\n<!-- docs/components/${d.id}.md -->\n\n${built.files[`docs/components/${d.id}.md`]}`),
].join("");
const publicFiles = {
  ...built.files,
  "public/llms.txt": llms,
  "public/llms-full.txt": llmsFull,
  "public/components.json": json,
  ...Object.fromEntries(DOCS.map(([src, out]) => [`public/docs/${out}`, src === "docs/QUICK_REF.md" ? nextQuickRef : read(src)])),
  ...Object.fromEntries(Object.entries(built.files).filter(([k]) => k.startsWith("docs/components/")).map(([k, v]) => [`public/${k}`, v])),
};
// Drift between the docs and the code (both modes fail): examples import only real exports and say which components
// they document, every component has a doc, every component / hook is named in DESIGN_SYSTEM.md, every style has a
// column in STYLES.md.
const drift = [...built.problems];
for (const c of manifest.components) if (!docOf[c.name]) drift.push(`${c.module}: component ${c.name} has no doc (add it to "components" of an examples/<id>/meta.json)`);
const designSystem = read("docs/DESIGN_SYSTEM.md");
for (const i of [...manifest.components, ...manifest.hooks])
  if (!new RegExp(`\\b${i.name}\\b`).test(designSystem)) drift.push(`docs/DESIGN_SYSTEM.md: ${i.kind} ${i.name} (${i.module}) is not described`);
const stylesDoc = read("docs/STYLES.md");
const styleHead = stylesDoc.split("\n").find((l) => l.startsWith("| |")) || "";
for (const st of styleList.styles) {
  if (!styleHead.includes(st.name)) drift.push(`docs/STYLES.md: style ${st.name} (${st.id}) has no column in the table`);
  for (const p of st.palettes) if (!stylesDoc.includes(`| ${st.name} | ${p.name}`) && !stylesDoc.includes(`| ${st.name} | **${p.name}**`)) drift.push(`docs/STYLES.md: palette ${st.name} / ${p.name} has no row in the Palettes table`);
}
if (drift.length) {
  console.error(`docs and code out of sync:\n- ${drift.join("\n- ")}`);
  process.exit(1);
}

const manifestPath = join(root, "components.json");
if (process.argv.includes("--check")) {
  const stale = [];
  if (!existsSync(manifestPath) || readFileSync(manifestPath, "utf8") !== json) stale.push("components.json");
  if (quickRef !== nextQuickRef) stale.push("docs/QUICK_REF.md (component inventory)");
  for (const [rel, text] of Object.entries(publicFiles)) if (!existsSync(join(root, rel)) || read(rel) !== text) stale.push(rel);
  if (stale.length) {
    console.error(`stale generated docs (run node scripts/build-manifest.mjs): ${stale.join(", ")}`);
    process.exit(1);
  }
  console.log(`components.json up to date (${manifest.components.length} components, ${manifest.constants.length} constants)`);
} else {
  writeFileSync(manifestPath, json);
  writeFileSync(quickRefPath, nextQuickRef);
  // Component docs are regenerated as a set: a removed doc must not linger.
  for (const dir of ["docs/components", "public/docs/components"]) rmSync(join(root, dir), { recursive: true, force: true });
  for (const [rel, text] of Object.entries(publicFiles)) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), text);
  }
  console.log(`wrote components.json (${manifest.components.length} components, ${manifest.hooks.length} hooks, ${manifest.constants.length} constants, ${iconNames.length} icons)`);
}
